-- | Initializes a 'SymbolEnv' with a 'Query' declaration.
--
-- /Precondition/: 'RelationDeclaration's must have been initialized in the 'SymbolEnv'
--
-- @since 0.0.1
initEnvWithQuery
  :: SymbolState σ
  => SymbolEnv
  -- ^ The 'SymbolEnv'
  -> Query
  -- ^ The 'Query'
  -> FixenPass σ SymbolEnv
initEnvWithQuery env q = do
  _ <- validateQuery q env
  let q_repr = simpleIdentifier $ q ^. name
  -- perform the insertion if it doesn't already exist
  case env ^. queryInfos . at q_repr of
    Just _ -> return env
    Nothing -> return $ env & queryInfos . at q_repr ?~ q

