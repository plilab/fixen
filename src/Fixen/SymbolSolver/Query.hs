-- | Validates a 'Query' declaration. The rules are:
--
-- * __Against Other Queries__: The query being declared must not have the same
--   name as other queries.
-- * __Against Extern Symbols__: The query being declared must not have the
--   same name as an external symbol. Note that a symbol is considered
--   \"external\" if it is not declared within the Fixen program.
-- * __Against Relations__: The relation being queried must exist and have the
--   right arity.
-- * __Against Fixen-generated Terms__: The query being declared must not have
--   the same name as any term generated by Fixen.
-- * __Against Prelude Terms__: A warning is emitted whenever the query being
--   declared has the same name as a term in Prelude.
--
-- @since 0.0.1
validateQuery :: SymbolState σ => SymbolValidator σ Query
validateQuery = validate r
  where
    r =
      [ againstOtherQueries
      , againstExtern
      , matchRelationArity
      , againstPrelude
      , againstFixen
      ]

    againstOtherQueries =
      validateNamed
        ( validateAgainstQuery
            "another query declaration with the same name"
        )

    againstExtern =
      validateNamed
        (validateAgainstExtern "query declaration" queryValidationErrorNotes)

    againstPrelude =
      validateNamed
        (warnAgainstPreludeLowercase "query declaration" "query declaration")

    againstFixen =
      validateNamed
        (validateAgainstFixenLowercase "query declaration" "query declaration")

    matchRelationArity q env =
      let rel = queryRel q
       in relationExistsAndHasRightArity rel "query" env
